#!/usr/bin/env python3
"""Generate docs/languages.md (the language support matrix) and check it against tests/test_langs.py.
Run: python3 tests/make_language_docs.py        (check: python3 tests/make_language_docs.py --check)

Every language in test_langs.CFG must have an entry here, and every entry must be in CFG, so the matrix cannot drift from the tests."""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGS = {
    "python": ("`ast` (stdlib)", "FastAPI (routers with `prefix`), Flask (+ blueprints, `add_url_rule`), Django (`path`/`re_path`, DRF `router.register`), aiohttp, Tornado, Starlette, Sanic, gRPC servicers, AWS Lambda handlers, Celery, click/typer/argparse",
               "`include_router(prefix=)` and Django `include()` prefixes across files are not joined; DRF viewset `@action` routes are not expanded"),
    "javascript": ("regex spec", "Express/Koa/Fastify/Hono-style `x.verb('/path')`, `app.route().get()`, router mounts in the same file, Hapi, tRPC, cron/commander/BullMQ, React JSX component references, Angular `HttpClient` calls",
                   "router mounts across files, Fastify `register({prefix})`, Next.js server actions"),
    "typescript": ("regex spec", "all of JavaScript plus NestJS (controllers, guards, constructor DI typed receivers, `@MessagePattern`, `@Cron`), Next.js `pages/api` and `app/**/route.ts`, tsconfig `paths` import resolution",
                   "Angular DI beyond constructor parameters; decorators that generate routes dynamically"),
    "go": ("regex spec", "net/http (incl. 1.22 `\"GET /x\"` patterns), chi, gin/echo/fiber verb methods, gorilla `.Methods`, gRPC `Register*Server`, cobra, cron; receivers, embedded structs, `go.mod` imports",
           "gRPC method handlers are not bound to the service entry; middleware groups are not followed"),
    "java": ("regex spec", "Spring (`*Mapping`, class prefix), JAX-RS, Micronaut-style `@Get/@Post`, Servlets (`doGet/doPost`), Vert.x routers, Kafka/Rabbit/SQS/JMS listeners, `@Scheduled`; JDBC/JPA sinks",
             "Struts, Spring functional routes, Quarkus-specific annotations"),
    "kotlin": ("regex spec", "Spring-style controllers, Ktor routing (handler = enclosing function), extension functions as methods, primary-constructor DI typed receivers",
               "Ktor nested `route(\"/x\") { }` prefixes"),
    "scala": ("regex spec", "Akka HTTP (`path(\"x\") { post { } }`), http4s (`case POST -> Root / \"x\"`), Scalatra-style, traits and `extends ... with`",
              "Play `conf/routes` is not parsed"),
    "csharp": ("regex spec", "ASP.NET MVC attributes (`[Route]`, `[HttpGet]`, `[Authorize]`), minimal APIs, Azure Functions (HTTP/timer/queue triggers), interface-typed DI resolved to implementations",
               "SignalR hubs, Blazor components"),
    "ruby": ("regex spec", "Rails (`routes.rb` with `resources`, `namespace`; controllers; `before_action`), Sinatra/Grape (`get '/x' do`), Sidekiq workers, `X.new` constructors, `require_relative`",
             "Hanami, Rails concerns and mixin dispatch"),
    "php": ("regex spec", "Laravel (`Route::`, groups, `resource`, middleware), Symfony routes, Slim, WordPress hooks and REST routes, PSR-4 class resolution via `composer.json`, constructor-promotion DI",
            "CodeIgniter/Yii/CakePHP controller conventions"),
    "rust": ("regex spec", "actix-web (attributes, resources), axum routes, Rocket attributes, warp, tonic (`async_trait` impls), clap, lambda_runtime, cron; `impl` and `trait` owners, `mod`/`use crate::` resolution",
             "macro-generated routes; trait-object dispatch beyond `impl` lookup"),
    "swift": ("regex spec", "Vapor routes (`app.get(\"x\", use: Handler(...).method)`), `extension` owners, SwiftUI/Foundation library calls",
              "SwiftUI screens as entry points, Kitura"),
}
ROWS = ["declarations", "imports", "calls", "objects and classes", "libraries", "entry points", "sources", "sinks", "auth evidence", "roles", "coverage"]


def cfg_keys() -> set:
    tree = ast.parse((ROOT / "tests" / "test_langs.py").read_text())
    for n in tree.body:
        if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "CFG":
            return {k.value for k in n.value.keys}
    return set()


def build() -> str:
    L = ["# Language support", "",
         "Every language below passes the same eleven-row conformance matrix in `tests/test_langs.py`: one realistic scenario per language (entry point, controller, service reached through a typed receiver, repository, library call, string-built SQL sink, an override, a test file and a generated file). This page is generated by `tests/make_language_docs.py` and checked against the test, so it cannot drift.", "",
         "## What \"covered\" means", "", "| # | Capability | Result required |", "| --- | --- | --- |",
         "| 1 | declarations | functions, methods and classes with qualified names and spans; strings and comments never produce calls |",
         "| 2 | imports | in-repo imports resolve to files (`use`, `import`, `require`, `mod`, PSR-4, tsconfig paths, `go.mod`); externals become `package` nodes |",
         "| 3 | calls | function, method, static, constructor, chained and callback calls resolved with a confidence; the rest are counted, never dropped silently |",
         "| 4 | objects and classes | typed receivers (constructor, annotation, injected field), class hierarchy, `overrides`, `implements`, `uses_type`, class-level call graph |",
         "| 5 | libraries | `calls_lib` edges from code to external packages, with the API names |",
         "| 6 | entry points | each framework in the table below bound to its handler |",
         "| 7 | sources | user-controlled inputs for those frameworks |",
         "| 8 | sinks | SQL, command, SSRF, code, deserialization, template, XSS, path, redirect, NoSQL, LDAP, XPath, XXE (and memory, format, TLS, unsafe code where they apply) with safe/unsafe verdicts |",
         "| 9 | auth evidence | the framework's route-, class- and middleware-level markers recognised |",
         "| 10 | roles | test and generated files by language-specific rules |",
         "| 11 | coverage | resolution accounting exists and the scenario's declared path resolved |", "",
         "## Matrix", "", "| Language | Parser | Frameworks and entry points | Known gaps |", "| --- | --- | --- | --- |"]
    for lang, (parser, fw, gap) in LANGS.items():
        L.append(f"| **{lang}** | {parser} | {fw} | {gap} |")
    L += ["", "Parsing is line-based and heuristic outside Python. Edges found that way carry confidence `medium` or `low`, and anything that cannot be resolved (dynamic dispatch, reflection, DI containers, macro-generated code) is listed in `system/coverage.md` with citations instead of being hidden. A source-to-sink link is always a candidate path, never proof.", ""]
    return "\n".join(L)


def main() -> int:
    keys = cfg_keys()
    if keys != set(LANGS):
        print("languages in tests/test_langs.py and tests/make_language_docs.py differ:", sorted(keys ^ set(LANGS)))
        return 1
    target = ROOT / "docs" / "languages.md"
    text = build()
    if "--check" in sys.argv:
        ok = target.is_file() and target.read_text() == text
        print("docs/languages.md is up to date" if ok else "docs/languages.md is stale: run python3 tests/make_language_docs.py")
        return 0 if ok else 1
    target.write_text(text)
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
