def classify(rel: str, head: str = "") -> dict:
    """Role for one file from its path and (optionally) its first bytes. Returns {role, sub, signals, confidence}."""
    p = rel.replace("\\", "/")
    name = p.rsplit("/", 1)[-1]
    suffix = "." + name.rsplit(".", 1)[-1].lower() if "." in name else ""
    stem = name.rsplit(".", 1)[0] if "." in name else name

    def out(role, sub=None, signals=None, conf="high"):
        return {"role": role, "sub": sub, "signals": signals or [], "confidence": conf}

    if GENERATED_NAME.search(p):
        return out("generated", signals=["generated file name/lockfile"])
    if head and GENERATED_HEAD.search(head[:1500]) and suffix in CODE_EXT:
        return out("generated", signals=["generated-code header"])
    if FIXTURE_PATH.search(p):
        return out("fixture", signals=["fixture/sample/mock directory"])
    if TEST_PATH.search(p):
        return out("test", signals=["test path/name"])
    if MIGRATION_PATH.search(p):
        return out("migration", signals=["migration path"])
    if PIPELINE_PATH.search(p):
        return out("pipeline", sub=_pipeline_sub(p), signals=["CI/CD pipeline path"])
    if suffix in IAC_EXT or name.endswith(".tf.json"):
        return out("iac", sub=IAC_EXT.get(suffix, "terraform"), signals=["infrastructure-as-code extension"])
    if IAC_PATH.search(p):
        return out("iac", sub=_iac_sub(p), signals=["infrastructure/deployment path"])
    if suffix in (".yaml", ".yml", ".json") and head:
        if PIPELINE_KIND.search(head):
            return out("pipeline", sub="argo/tekton", signals=["workflow/pipeline resource kind"])
        if GITOPS_KIND.search(head):
            return out("iac", sub="gitops", signals=["GitOps resource kind"])
        if K8S_KIND.search(head) and "apiVersion" in head:
            return out("iac", sub="kubernetes", signals=["Kubernetes manifest"])
        if suffix != ".json" and CFN_HEAD.search(head) and ("AWSTemplateFormatVersion" in head or "AWS::" in head):
            return out("iac", sub="cloudformation", signals=["CloudFormation template"])
        if suffix == ".json" and ARM_HEAD.search(head) and "deploymentTemplate" in head:
            return out("iac", sub="arm", signals=["ARM template"])
    if DOC_NAME.match(name) or DOC_DIR.search(p) or suffix in DOC_EXT:
        return out("docs", signals=["documentation"])
    if BUILD_NAME.match(name):
        return out("build", signals=["build/manifest file"])
    if TOOLING_DIR.search(p) or suffix in TOOLING_EXT:
        if suffix in CODE_EXT or suffix in TOOLING_EXT:
            return out("tooling", signals=["scripts/tools directory or shell script"])
    if suffix in CODE_EXT:
        if UTILITY_DIR.search(p) or UTILITY_STEM.match(stem):
            return {"role": "code", "sub": "utility-hint", "signals": ["helper-style name/dir"], "confidence": "medium", "lang": CODE_EXT[suffix]}
        return {"role": "code", "sub": None, "signals": [], "confidence": "medium", "lang": CODE_EXT[suffix]}
    if suffix in CONFIG_EXT or name.startswith(".") or name.endswith((".example", ".sample")):
        return out("config", signals=["configuration file"])
    return out("other", conf="low")


def _pipeline_sub(p: str) -> str:
    for rx, name in ((r"\.github/", "github-actions"), (r"azure-?pipelines|\.pipelines?/", "azure-pipelines"), (r"gitlab", "gitlab-ci"),
                     (r"Jenkinsfile|vars/", "jenkins"), (r"circleci", "circleci"), (r"tekton", "tekton"), (r"cloudbuild", "cloud-build"),
                     (r"drone", "drone"), (r"bitbucket", "bitbucket"), (r"buildkite", "buildkite"), (r"travis", "travis")):
        if re.search(rx, p):
            return name
    return "pipeline"


def _iac_sub(p: str) -> str:
    for rx, name in ((r"Pulumi", "pulumi"), (r"cdk\.json", "cdk"), (r"kustomiz", "kustomize"), (r"Chart\.ya?ml|charts?/|helm", "helm"),
                     (r"ansible|playbook|roles/|inventory", "ansible"), (r"\.pkr\.hcl", "packer"), (r"azuredeploy|main\.parameters", "arm"),
                     (r"serverless|samconfig", "serverless"), (r"crossplane", "crossplane"), (r"k8s|kubernetes|manifests|overlays|base/|deploy", "kubernetes")):
        if re.search(rx, p):
            return name
    return "iac"


GITOPS_SUBS = {"kubernetes", "kustomize", "helm", "gitops"}
IAC_SUBS = {"terraform", "bicep", "arm", "cloudformation", "pulumi", "cdk", "ansible", "packer", "serverless", "crossplane", "iac"}


def classify_repo_files(root: Path, excludes: list[str], cap: int = 20000) -> list[dict]:
    """Classify every non-binary file in a repo checkout. Secret files are listed as role config without being read."""
    rows = []
    for p, rel in walk_files(root, excludes):
        if len(rows) >= cap:
            break
        if is_secret_file(rel):
            rows.append({"path": rel, "role": "config", "sub": "secret-file-not-read", "signals": ["secret file (not read)"], "confidence": "high"})
            continue
        if is_binary(p):
            continue
        suffix = p.suffix.lower()
        head = ""
        if suffix in CODE_EXT or suffix in (".yaml", ".yml", ".json"):
            head = read_text(p, max_bytes=2500) or ""
        row = classify(rel, head)
        row["path"] = rel
        row["lang"] = row.get("lang") or CODE_EXT.get(suffix)
        rows.append(row)
    return rows


# ---------------------------------------------------------------- repo kind

def repo_kind(role_counts: dict, sub_counts: dict, entry_counts: dict, repo: str, has_container: bool, lib_hint: bool) -> dict:
    """Decide application | service | library | iac | cicd-pipeline | gitops-config | docs | tooling | mixed."""
    code = role_counts.get("core", 0) + role_counts.get("utility", 0) + role_counts.get("code", 0)
    iac_files = sub_counts.get("iac_infra", 0)
    gitops_files = sub_counts.get("iac_gitops", 0)
    pipe = role_counts.get("pipeline", 0)
    tooling = role_counts.get("tooling", 0)
    docs = role_counts.get("docs", 0)
    # documentation only decides the kind when the repo has nothing else of substance
    subst = code + iac_files + gitops_files + pipe + tooling + role_counts.get("config", 0) + role_counts.get("build", 0)
    if code + iac_files + gitops_files + pipe == 0:
        subst += docs
    cfg = role_counts.get("config", 0) + role_counts.get("build", 0)
    if subst == cfg and subst > 0:
        return {"repo_kind": "config", "secondary_kinds": [], "signals": ["only configuration/contract/build files (no code, IaC or pipelines)"], "confidence": "medium"}
    if subst == 0:
        return {"repo_kind": "tooling", "secondary_kinds": [], "signals": ["no classifiable files"], "confidence": "low"}
    hints = {k: bool(rx.search(repo)) for k, rx in NAME_HINTS.items()}
    shares = {
        "application": code / subst + (0.1 if has_container and code else 0),
        "iac": iac_files / subst + (0.2 if hints["iac"] else 0) * (1 if iac_files else 0),
        "gitops-config": gitops_files / subst + (0.2 if hints["gitops"] else 0) * (1 if gitops_files else 0),
        "cicd-pipeline": pipe / subst + (0.2 if hints["pipeline"] else 0) * (1 if pipe else 0),
        "docs": docs / subst if code + iac_files + gitops_files + pipe == 0 else 0,
        "tooling": tooling / subst,
    }
    # CI definitions inside an application repo are normal; only count them when pipeline files dominate
    order = sorted(shares.items(), key=lambda kv: -kv[1])
    primary, top = order[0]
    sig = [f"{k} share {round(v * 100)}%" for k, v in order if v >= 0.05]
    sig += [f"name hint: {k}" for k, v in hints.items() if v]
    sig += [f"{n} {k}" for k, n in entry_counts.items() if n]
    secondary = [k for k, v in order[1:] if v >= 0.25 and k in ("application", "iac", "gitops-config", "cicd-pipeline")]
    infra_pair = {"iac", "gitops-config"}
    mixed_secondary = [k for k in secondary if not (primary in infra_pair and k in infra_pair)]
    if primary == "application":
        entries = sum(entry_counts.get(k, 0) for k in ("endpoint", "consumer", "cron_job", "cli_command"))
        service = sum(entry_counts.get(k, 0) for k in ("endpoint", "consumer", "cron_job")) > 0 or has_container
        kind = "library" if (lib_hint and not entries and not has_container) else ("service" if service else "application")
    else:
        kind = primary
    if primary in ("iac", "gitops-config", "cicd-pipeline", "application") and mixed_secondary and top < 0.7:
        # a repo that clearly holds two kinds of content is reported as mixed with the dominant one first
        return {"repo_kind": "mixed", "primary_kind": kind, "secondary_kinds": mixed_secondary, "signals": sig, "confidence": "medium"}
    return {"repo_kind": kind, "secondary_kinds": secondary, "signals": sig, "confidence": "high" if top >= 0.6 else "medium"}


# ---------------------------------------------------------------- graph pass

ENTRY_KINDS = ("endpoint", "consumer", "cron_job", "cli_command")
IO_EDGES = {"reads", "writes", "publishes", "consumes", "reaches_sink", "http_calls", "grpc_calls", "spawns", "reads_env"}


def _path_of(node: dict) -> str:
    if node.get("path"):
        return node["path"]
    m = re.match(r"^[^/]+/(.+):\d+(?:-\d+)?$", node.get("citation") or "")
    return m.group(1) if m else ""


def apply(link, roots: dict, out: Path) -> dict:
    """Post-link pass on a graph_build.Linker: assigns roles to files and repo kinds to repos, writes the evidence and
    code-map files, and returns summary stats. Never raises on odd repos."""
    stats = {}
    nodes, edges = link.nodes, list(link.edges.values())
    by_src = defaultdict(list)
    for e in edges:
        by_src[e["src"]].append(e)
    fn_file = {nid: _path_of(n) for nid, n in nodes.items() if n["kind"] in ("function", "method", "class")}
    file_of_repo = defaultdict(set)
    for nid, n in nodes.items():
        if n["kind"] == "file":
            file_of_repo[n["repo"]].add(n["path"])

    for repo, root in roots.items():
        excludes = repo_excludes(out).get(repo, [])
        rows = classify_repo_files(Path(root), excludes)
        tool_code = [r for r in rows if r["role"] == "tooling" and r.get("lang") and r["lang"] != "sql"]
        if tool_code and len(tool_code) > sum(1 for r in rows if r["role"] == "code"):
            # most of the repo's code lives under scripts/ or tools/ (CLI tools, plugins): that code is the product, not tooling
            for r in tool_code:
                r.update(role="code", sub=None, signals=["most of this repo's code lives under scripts/tools"], confidence="medium")
        by_path = {r["path"]: r for r in rows}
        # entry points and the files that define them / the handlers they reach
        entry_files, handlers, entry_counts = set(), set(), Counter()
        for nid, n in nodes.items():
            if n["kind"] in ENTRY_KINDS and (n["repo"] == repo or n["kind"] == "endpoint" and n["citation"].startswith(repo + "/")):
                p = _path_of(n)
                if p:
                    entry_files.add(p)
                entry_counts[n["kind"]] += 1
                for e in by_src.get(nid, []):
                    if e["kind"] == "routes_to":
                        handlers.add(e["dst"])
        reach = set(handlers)
        frontier = list(handlers)
        while frontier and len(reach) < 20000:
            cur = frontier.pop()
            for e in by_src.get(cur, []):
                if e["kind"] in ("calls", "routes_to", "contains") and e["dst"] not in reach and e["dst"] in nodes \
                        and nodes[e["dst"]]["kind"] in ("function", "method", "class"):
                    reach.add(e["dst"])
                    frontier.append(e["dst"])
        reach_files = {fn_file.get(x) for x in reach if fn_file.get(x)}
        importers = defaultdict(set)
        for e in edges:
            if e["kind"] == "imports" and e["dst"].startswith(f"file:{repo}:"):
                importers[e["dst"]].add(e["src"])
            elif e["kind"] == "calls" and e["dst"] in fn_file and e["src"] in fn_file and fn_file[e["src"]] != fn_file[e["dst"]]:
                importers[f"file:{repo}:{fn_file[e['dst']]}:"].add(f"file:{repo}:{fn_file[e['src']]}:")
        io_files = set()
        for nid, n in nodes.items():
            if n["kind"] in ("function", "method") and n["repo"] == repo:
                if any(e["kind"] in IO_EDGES - {"reads_env"} for e in by_src.get(nid, [])):
                    io_files.add(n["path"])
        for path in file_of_repo.get(repo, ()):
            row = by_path.get(path)
            if row is None:
                continue
            fid = f"file:{repo}:{path}:"
            if row["role"] != "code":
                continue
            hint = row.get("sub") == "utility-hint"
            fan_in = len(importers.get(fid, ()))
            sigs = list(row["signals"])
            if path in entry_files:
                role, conf, sigs = "core", "medium", sigs + ["defines an entry point"]
            elif hint and path not in io_files:
                role, conf = "utility", "medium"
                sigs += ([f"imported by {fan_in} files"] if fan_in else [])
            elif path in io_files:
                role, conf, sigs = "core", "medium", sigs + ["owns I/O (data store, queue, outbound call, sink)"]
            elif fan_in >= 3:
                role, conf, sigs = "utility", "medium", sigs + [f"imported/called by {fan_in} files, no entry point or I/O"]
            elif path in reach_files:
                role, conf, sigs = "core", "medium", sigs + ["reached from an entry point"]
            else:
                role, conf, sigs = "core", "low", sigs + ["no entry-point, I/O or helper signal; default"]
            row.update(role=role, signals=sigs, confidence=conf, fan_in=fan_in)
            fnode = nodes.get(fid)
            if fnode is not None:
                at = fnode.setdefault("attrs", {})
                at.update(role=role, role_signals=sigs[:6], role_confidence=conf, fan_in=fan_in)
                fnode["tags"] = sorted(set((fnode.get("tags") or []) + [f"role:{role}"]))
        for row in rows:
            if row["role"] == "code":  # code files with no graph node (empty, unparsed language, or too large)
                row.update(role="other", sub="unparsed", signals=["no graph node (empty file or language without an extractor)"], confidence="low")
        counts = Counter(r["role"] for r in rows)
        subs = Counter()
        for r in rows:
            if r["role"] == "iac":
                subs["iac_gitops" if r.get("sub") in GITOPS_SUBS else "iac_infra"] += 1
        meta = load_manifest_hints(Path(root))
        kind = repo_kind(counts, subs, entry_counts, repo, meta["container"], meta["library"])
        rn = nodes.get(f"repo:{repo}::{repo}")
        if rn is not None:
            rn.setdefault("attrs", {}).update(repo_kind=kind["repo_kind"], repo_kind_signals=kind["signals"][:8],
                                              secondary_kinds=kind.get("secondary_kinds", []), role_counts=dict(counts))
            if kind.get("primary_kind"):
                rn["attrs"]["primary_kind"] = kind["primary_kind"]
        write_outputs(out, repo, rows, counts, kind, entry_counts, nodes, [e for e in edges if e["kind"] == "tested_by"])
        stats[repo] = {"kind": kind["repo_kind"], "roles": dict(counts)}
    return stats


def load_manifest_hints(root: Path) -> dict:
    container = any((root / n).is_file() for n in ("Dockerfile", "docker-compose.yml", "docker-compose.yaml", "compose.yaml")) or \
        any(root.glob("*/Dockerfile"))
    lib = False
    pj = root / "package.json"
    if pj.is_file():
        t = read_text(pj, max_bytes=40000) or ""
        lib = bool(re.search(r'"(main|module|exports|types)"\s*:', t)) and not re.search(r'"private"\s*:\s*true', t) and not container
    for f in ("setup.py", "pyproject.toml"):
        if (root / f).is_file() and not container:
            t = read_text(root / f, max_bytes=40000) or ""
            lib = lib or bool(re.search(r"(?m)^\[project\]|packages\s*=|setuptools|find_packages", t)) and not re.search(r"(?i)fastapi|flask|django|uvicorn", t)
    return {"container": container, "library": lib}


def write_outputs(out: Path, repo: str, rows: list, counts: Counter, kind: dict, entry_counts: Counter, nodes: dict, tested_edges: list) -> None:
    ev = {"repo": repo, "repo_kind": kind, "role_counts": dict(counts), "entry_points": dict(entry_counts),
          "files": [{k: r.get(k) for k in ("path", "role", "sub", "lang", "confidence", "signals", "fan_in") if r.get(k) not in (None, [])}
                    for r in rows[:5000]], "truncated": len(rows) > 5000,
          "note": "core/utility are [inferred]; signals show why. Path and content rules decide the other roles."}
    atomic_write(out / "evidence" / f"file-roles-{repo}.json", json.dumps(ev, indent=1))
    core = sorted((r for r in rows if r["role"] == "core"), key=lambda r: (-(r.get("fan_in") or 0), r["path"]))
    util = sorted((r for r in rows if r["role"] == "utility"), key=lambda r: r["path"])
    tests = [r for r in rows if r["role"] == "test"]
    tested = set()
    for e in tested_edges:
        n = nodes.get(e["src"])
        if n is not None:
            tested.add(_path_of(n))
    L = [f"# Code map: {md_safe(repo)}", "",
         "> **ckb provenance**", f"> - Sources: `{md_safe(repo)}` (file roles from `evidence/file-roles-{md_safe(repo)}.json`)",
         "> - Method: path/content rules for most roles; graph signals for core vs utility (always [inferred])",
         "> - Excluded: vendored, binaries, symlinks, secret files (listed, not read)", "",
         "## Repo kind", "",
         f"- **{md_safe(kind['repo_kind'])}**" + (f" (primary: {md_safe(kind.get('primary_kind'))}; also {md_safe(', '.join(kind.get('secondary_kinds', [])))})" if kind["repo_kind"] == "mixed" else
                                                  (f" (also: {md_safe(', '.join(kind.get('secondary_kinds', [])))})" if kind.get("secondary_kinds") else ""))
         + f" [inferred], confidence {kind['confidence']}",
         f"- Signals: {md_safe('; '.join(kind['signals']))}", "", "## Files by role", "", "| Role | Files |", "| --- | --- |"]
    L += [f"| {md_safe(k)} | {v} |" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    L += ["", "## Core application files [inferred]", "", "| File | Why | Fan-in |", "| --- | --- | --- |"]
    L += [f"| `{md_safe(r['path'])}` | {md_safe('; '.join(r['signals'][-2:]))} | {r.get('fan_in', 0)} |" for r in core[:40]] or ["| [n/a] none | | |"]
    if len(core) > 40:
        L.append(f"\n{len(core) - 40} more core files are in the evidence JSON.")
    L += ["", "## Utility files [inferred]", "", "| File | Why |", "| --- | --- |"]
    L += [f"| `{md_safe(r['path'])}` | {md_safe('; '.join(r['signals']))} |" for r in util[:40]] or ["| [n/a] none | |"]
    other = [r for r in rows if r["role"] in ("iac", "pipeline")]
    if other:
        subs = Counter(f"{r['role']}/{r.get('sub') or '-'}" for r in other)
        L += ["", "## Infrastructure and pipeline files", "", "| Kind | Files |", "| --- | --- |"]
        L += [f"| {md_safe(k)} | {v} |" for k, v in sorted(subs.items())]
    L += ["", "## Tests", "", f"{len(tests)} test file(s)" + (": " + ", ".join(f"`{md_safe(r['path'])}`" for r in tests[:12]) + (" …" if len(tests) > 12 else "") if tests else " [unknown] none found")]
    untested = [r["path"] for r in core if r["path"] not in tested]
    L += ["", f"Core files with no `tested_by` link ({len(untested)}): " + (", ".join(f"`{md_safe(x)}`" for x in untested[:15]) + (" …" if len(untested) > 15 else "") if untested else "none"),
          "(a missing link can also mean the tests call the code in a way the extractor could not resolve)", ""]
    atomic_write(out / "repos" / repo / "code-map.md", "\n".join(L))


def run(out: Path, repo: str | None = None) -> dict:
    """Standalone use: rebuild a Linker from fragments just to classify; see graph_build.build for the normal path."""
    import graph_build
    roots = {k: v for k, v in repo_roots_for_output(out).items() if not k.startswith("ctx") and (repo is None or k == repo)}
    link = graph_build.Linker(graph_build.load_fragments(out, roots), roots, out).build()
    return apply(link, roots, out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--repo")
    a = ap.parse_args()
    print(json.dumps(run(Path(a.out).resolve(), a.repo), indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
